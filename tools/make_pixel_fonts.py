def parse(rows):
    """→ (ширина, список (строка, колонка)); строка 0 — верх заглавных, −1 — над ними, 7 — ниже."""
    above = [r[1:] for r in rows if r.startswith("^")]
    below = [r[1:] for r in rows if r.startswith("_")]
    body = [r for r in rows if not r.startswith(("^", "_"))]
    assert len(body) == 7, rows
    width = max([len(r) for r in body] + [len(r) for r in above + below])
    cells = []
    for i, r in enumerate(above):
        cells += [(-len(above) + i, c) for c, ch in enumerate(r) if ch == "#"]
    for i, r in enumerate(body):
        cells += [(i, c) for c, ch in enumerate(r) if ch == "#"]
    for i, r in enumerate(below):
        cells += [(7 + i, c) for c, ch in enumerate(r) if ch == "#"]
    return width, cells


def cell_box(row, col):
    """Квадрат пикселя в единицах шрифта (x0, y0, x1, y1); левый отступ — полпикселя."""
    x0 = P // 2 + col * P
    y1 = CAP - row * P
    return x0, y1 - P, x0 + P, y1


def draw_block(pen, cells):
    """Сплошные квадраты: соседние в строке пиксели сливаем в одну полосу (меньше контуров)."""
    rows = {}
    for r, c in cells:
        rows.setdefault(r, []).append(c)
    for r, cols in rows.items():
        cols.sort()
        start = prev = cols[0]
        for c in cols[1:] + [None]:
            if c is not None and c == prev + 1:
                prev = c
                continue
            x0, y0, _, y1 = cell_box(r, start)
            x1 = cell_box(r, prev)[2]
            # контур по часовой стрелке (внешний контур TrueType)
            pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
            if c is not None:
                start = prev = c


def draw_dots(pen, cells):
    """Круглые «светодиоды»: окружность из 8 дуг (квадратичные кривые TrueType), по часовой стрелке."""
    r = P * 0.40
    for row, col in cells:
        x0, y0, x1, y1 = cell_box(row, col)
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        k = r / math.cos(math.pi / 8)  # опорные точки дуг — на описанном восьмиугольнике
        pts = []
        for i in range(8):
            a = -i * math.pi / 4  # по часовой стрелке
            pts.append(("on", cx + r * math.cos(a), cy + r * math.sin(a)))
            b = a - math.pi / 8
            pts.append(("off", cx + k * math.cos(b), cy + k * math.sin(b)))
        pen.moveTo((round(pts[0][1]), round(pts[0][2])))
        for i in range(1, 17, 2):
            off = pts[i]
            on = pts[(i + 1) % 16]
            pen.qCurveTo((round(off[1]), round(off[2])), (round(on[1]), round(on[2])))
        pen.closePath()


def build(family, ps, draw, filename):
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "assets", "fonts", filename)
    order = [".notdef", "space"]
    cmap = {32: "space", 160: "space"}
    glyphs, adv = {}, {}

    pen = TTGlyphPen(None)
    draw_block(pen, [(r, c) for r in range(7) for c in range(4) if r in (0, 6) or c in (0, 3)])
    glyphs[".notdef"] = pen.glyph()
    adv[".notdef"] = (4 + GAP) * P + P // 2
    glyphs["space"] = TTGlyphPen(None).glyph()
    adv["space"] = 3 * P + P // 2

    names = {}
    for ch, rows in G.items():
        key = id(rows)
        if key not in names:
            name = "uni%04X" % ord(ch)
            width, cells = parse(rows)
            pen = TTGlyphPen(None)
            draw(pen, cells)
            glyphs[name] = pen.glyph()
            adv[name] = (width + GAP) * P  # полпикселя слева + буква + промежуток (правые полпикселя)
            order.append(name)
            names[key] = name
        name = names[key]
        cmap[ord(ch)] = name
        low = ch.lower()
        if low != ch and ord(low) not in cmap:
            cmap[ord(low)] = name  # строчные — как заглавные

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    glyf = fb.font["glyf"]
    hmtx = {}
    for name in order:
        g = glyf[name]
        g.recalcBounds(glyf)
        hmtx[name] = (adv[name], getattr(g, "xMin", 0) if g.numberOfContours else 0)
    fb.setupHorizontalMetrics(hmtx)
    fb.setupHorizontalHeader(ascent=900, descent=-200)
    fb.setupNameTable({
        "familyName": family,
        "styleName": "Regular",
        "uniqueFontIdentifier": family + " Regular",
        "fullName": family,
        "psName": ps + "-Regular",
        "version": "Version 1.000",
        "copyright": family + " — пиксельный шрифт для Hora (MIT)",
    })
    fb.setupOS2(
        sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=0,
        usWinAscent=950, usWinDescent=250,
        sxHeight=CAP, sCapHeight=CAP,
        ulUnicodeRange1=(1 << 0) | (1 << 1) | (1 << 9),
        ulCodePageRange1=(1 << 0) | (1 << 2),
        achVendID="HORA",
    )
    fb.setupPost()
    fb.save(out)
    print("готово:", out, "глифов:", len(order))


if __name__ == "__main__":
    build("Hora Pixel", "HoraPixel", draw_dots, "HoraPixel.ttf")
    build("Hora Block", "HoraBlock", draw_block, "HoraBlock.ttf")
